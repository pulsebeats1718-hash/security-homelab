#!/usr/bin/env node
/**
 * Publish the built game (dist/) to Cloudflare Workers as ONE Worker with every file packed
 * inside it, instead of Workers static assets.
 *
 *   npm run deploy:cloudflare:embed            (builds first; extra arguments go to wrangler)
 *   npm run deploy:cloudflare:embed -- --dry-run
 *
 * Use this only where `npm run deploy:cloudflare` (the normal static-assets upload) cannot work:
 * wrangler's asset upload authenticates with a one-off upload key in the Authorization header,
 * and a network proxy that writes your API token into that header for every Cloudflare request
 * (as Claude's cloud sessions do) breaks it with "401 Unauthorized". This route only needs the
 * API token. Trade-offs: every file request counts as a Worker request (the free plan allows
 * 100,000 a day; static-asset requests are free and unlimited), and the whole build must stay
 * under the Worker size limit (3 MB compressed on the free plan, 10 MB on paid plans).
 *
 * It serves the same responses as the static-assets deploy: the rules in dist/_headers (from
 * public/_headers), the right content types, ETags with 304 replies, / → index.html, and 404 for
 * anything else. Everything it generates goes to .wrangler/embed/ (git-ignored).
 */
import { createHash } from 'node:crypto';
import { spawnSync } from 'node:child_process';
import { existsSync, mkdirSync, readFileSync, readdirSync, rmSync, writeFileSync } from 'node:fs';
import { dirname, join, relative, resolve, sep } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const dist = join(root, 'dist');
const out = join(root, '.wrangler', 'embed');
const NAME = 'phrasefall';

if (!existsSync(join(dist, 'index.html'))) {
  console.error('dist/ has no build. Run `npm run build` first.');
  process.exit(1);
}

const TYPES = {
  html: 'text/html; charset=utf-8',
  js: 'text/javascript; charset=utf-8',
  mjs: 'text/javascript; charset=utf-8',
  css: 'text/css; charset=utf-8',
  json: 'application/json; charset=utf-8',
  map: 'application/json; charset=utf-8',
  webmanifest: 'application/manifest+json; charset=utf-8',
  txt: 'text/plain; charset=utf-8',
  svg: 'image/svg+xml',
  png: 'image/png',
  jpg: 'image/jpeg',
  jpeg: 'image/jpeg',
  webp: 'image/webp',
  ico: 'image/x-icon',
  woff2: 'font/woff2',
  woff: 'font/woff',
};

/** dist/_headers → [{ pattern, headers }] (Cloudflare's format: a path line, then indented "Name: value" lines). */
function readHeaderRules(file) {
  if (!existsSync(file)) return [];
  const rules = [];
  for (const line of readFileSync(file, 'utf8').split('\n')) {
    if (!line.trim() || line.trim().startsWith('#')) continue;
    if (!/^\s/.test(line)) rules.push({ pattern: line.trim(), headers: {} });
    else if (rules.length) {
      const i = line.indexOf(':');
      if (i > 0) rules.at(-1).headers[line.slice(0, i).trim()] = line.slice(i + 1).trim();
    }
  }
  return rules;
}

function walk(dir) {
  return readdirSync(dir, { withFileTypes: true }).flatMap((e) => (e.isDirectory() ? walk(join(dir, e.name)) : [join(dir, e.name)]));
}

rmSync(out, { recursive: true, force: true });
mkdirSync(join(out, 'files'), { recursive: true });

const files = walk(dist)
  .map((f) => '/' + relative(dist, f).split(sep).join('/'))
  .filter((p) => p !== '/_headers' && p !== '/_redirects' && p !== '/.assetsignore')
  .sort();
const imports = [];
const table = [];
files.forEach((p, i) => {
  const body = readFileSync(join(dist, p));
  writeFileSync(join(out, 'files', `f${i}.bin`), body); // .bin files become binary (Data) modules
  const ext = p.split('.').pop().toLowerCase();
  const etag = `"${createHash('sha256').update(body).digest('hex').slice(0, 20)}"`;
  imports.push(`import f${i} from './files/f${i}.bin';`);
  table.push(`  ${JSON.stringify(p)}: { body: f${i}, type: ${JSON.stringify(TYPES[ext] ?? 'application/octet-stream')}, etag: ${JSON.stringify(etag)} },`);
});
writeFileSync(join(out, 'files.js'), `${imports.join('\n')}\n\nexport const FILES = {\n${table.join('\n')}\n};\n`);

const rules = readHeaderRules(join(dist, '_headers'));
writeFileSync(
  join(out, 'worker.js'),
  `// Generated by scripts/cloudflare-embed.mjs: serves the packed build of Phrasefall.
import { FILES } from './files.js';

const RULES = ${JSON.stringify(rules, null, 2)};
const DEFAULT_CACHE = 'public, max-age=0, must-revalidate';

const matches = (pattern, path) => (pattern.endsWith('*') ? path.startsWith(pattern.slice(0, -1)) : path === pattern);

function headersFor(path, file) {
  const h = new Headers({ 'Content-Type': file.type, ETag: file.etag, 'Cache-Control': DEFAULT_CACHE });
  for (const rule of RULES) if (matches(rule.pattern, path)) for (const [k, v] of Object.entries(rule.headers)) h.set(k, v);
  return h;
}

export default {
  async fetch(request) {
    if (request.method !== 'GET' && request.method !== 'HEAD') {
      return new Response('Method not allowed', { status: 405, headers: { Allow: 'GET, HEAD' } });
    }
    let path = new URL(request.url).pathname;
    try {
      path = decodeURIComponent(path);
    } catch {
      /* keep it encoded */
    }
    const file = FILES[path.endsWith('/') ? path + 'index.html' : path];
    if (!file) {
      return new Response('Not found', { status: 404, headers: { 'Content-Type': 'text/plain; charset=utf-8', 'X-Content-Type-Options': 'nosniff' } });
    }
    const headers = headersFor(path, file);
    const seen = (request.headers.get('If-None-Match') || '').split(',').map((t) => t.trim().replace(/^W\\//, ''));
    if (seen.includes(file.etag)) return new Response(null, { status: 304, headers });
    return new Response(request.method === 'HEAD' ? null : file.body, { headers });
  },
};
`
);

const wrangler = JSON.parse(readFileSync(join(root, 'wrangler.jsonc'), 'utf8').replace(/^\s*\/\/.*$/gm, ''));
writeFileSync(
  join(out, 'wrangler.json'),
  JSON.stringify({ name: wrangler.name ?? NAME, main: 'worker.js', compatibility_date: wrangler.compatibility_date, workers_dev: true }, null, 2) + '\n'
);

console.log(`Packed ${files.length} files from dist/ into .wrangler/embed/ (header rules: ${rules.length}).`);
const res = spawnSync('npx', ['--yes', 'wrangler@4', 'deploy', '--config', join(out, 'wrangler.json'), ...process.argv.slice(2)], { stdio: 'inherit', cwd: root });
process.exit(res.status ?? 1);
